def interp(pts,y):
    for (x1,y1),(x2,y2) in zip(pts,pts[1:]):
        if y1<=y<=y2: return x1+(x2-x1)*(y-y1)/(y2-y1)
    return pts[0][0] if y<pts[0][1] else pts[-1][0]
